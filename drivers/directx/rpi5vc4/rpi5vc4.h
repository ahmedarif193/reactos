/* ========================================================================
 * DMA packet stream
 *
 * The command/DMA buffer contents exchanged with the (future) user-mode
 * driver and generated by DxgkDdiPresent.  DxgkDdiRender validates and
 * copies this stream; DxgkDdiSubmitCommand executes it: V3D job packets
 * are queued to the CLE, everything else completes with the fence.
 * ====================================================================== */

#define RPI5VC4_DMA_PACKET_MAGIC    0x52355644u  /* 'DV5R' */

#define RPI5VC4_DMA_OP_NOP          0
#define RPI5VC4_DMA_OP_PRESENT      1
#define RPI5VC4_DMA_OP_V3D_JOB      2
#define RPI5VC4_DMA_OP_TFU_JOB      3
#define RPI5VC4_DMA_OP_CSD_JOB      4

typedef struct _RPI5VC4_DMA_PACKET
{
    ULONG Magic;
    ULONG Op;
    ULONG Length;                    /* total packet bytes incl. header */
    ULONG Reserved;
    union
    {
        struct
        {
            /* GPU virtual addresses (see RPI5VC4_V3D_SLAB_GPUVA) — OR,
             * when *AllocIndexPlusOne is nonzero, byte offsets within
             * that allocation (index-1 into the submission's allocation
             * list): DxgkDdiRender then emits patch locations and
             * DxgkDdiPatch relocates the dwords to real GPU VAs.  A
             * zeroed field keeps absolute-address behaviour. */
            ULONG BclStart;          /* binning list; Start==End = none  */
            ULONG BclEnd;
            ULONG RclStart;          /* render list                      */
            ULONG RclEnd;
            ULONG BclAllocIndexPlusOne;
            ULONG RclAllocIndexPlusOne;
            /* Per-job tile allocation (absolute GPU VAs).  Qms==0 means
             * "use the device-global binner overflow pool" (legacy smoke
             * path); a real v3dv job supplies all three. */
            ULONG Qma;               /* tile allocation memory address    */
            ULONG Qms;               /* tile allocation memory size       */
            ULONG Qts;               /* tile state data array address     */
        } V3dJob;
        struct
        {
            RECT DstRect;
            ULONG Color;
            ULONG Flags;             /* DXGK_PRESENTFLAGS.Value          */
        } Present;
        struct
        {
            /* UMD-encoded TFU register image:
             * [Icfg Iia Ica Iis Iua Ioc Ioa Ios Coef0..Coef3]. */
            UINT Regs[12];
        } TfuJob;
        struct
        {
            /* UMD-encoded compute dispatch: QUEUED_CFG0..CFG7. */
            ULONG Cfg[8];
        } CsdJob;
    };
} RPI5VC4_DMA_PACKET, *PRPI5VC4_DMA_PACKET;

