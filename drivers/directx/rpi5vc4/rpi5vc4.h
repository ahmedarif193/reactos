struct _RPI5VC4_DEVICE_EXTENSION
{
    /* dxgkrnl callback vtable captured at StartDevice. */
    DXGK_INTERFACE DxgkInterface;
    PDEVICE_OBJECT PhysicalDeviceObject;
    BOOLEAN Started;

    /* No firmware display (headless boot): the driver owns a RAM scanout
     * and reports a phantom monitor; HVS/PV stay untouched. */
    BOOLEAN Headless;
    PVOID HeadlessFbVa;
    PIO_WORKITEM HpdWorkItem;
    LONG HpdCheckQueued;
    KTIMER HpdTimer;
    KDPC HpdDpc;
    UCHAR Edid[128];
    BOOLEAN EdidValid;

    /* Firmware GOP scanout geometry (from DxgkCbAcquirePostDisplayOwnership). */
    PHYSICAL_ADDRESS FirmwareFrameBufferPhysical;
    PHYSICAL_ADDRESS FrameBufferPhysical;
    PVOID FrameBufferVa;              /* write-combined kernel mapping        */
    ULONG FrameBufferSize;
    ULONG ScreenWidth;
    ULONG ScreenHeight;
    ULONG PixelsPerScanLine;
    ULONG BitsPerPixel;
    ULONG BytesPerScanLine;
    D3DDDIFORMAT ColorFormat;

    /* Committed VidPN state. */
    BOOLEAN VidPnCommitted;
    BOOLEAN SourceVisible;

    /* Cached MMIO mapping of the HVS register block (mapped once, reused). */
    PVOID HvsBase;

    /* Cached MMIO mapping of the active PixelValve (mapped once, reused). */
    PVOID PixelValveBase;

    /* Validated cursor-plane location for the low-MMIO cursor move fast path. */
    ULONG HvsLptrsReg;
    ULONG HvsLptrsVal;
    ULONG HvsCursorHead;
    BOOLEAN HvsCursorFastValid;

    /* Active private display-list slot (0 = scanning the firmware head). */
    ULONG HvsActivePrivateSlot;

    /* Silicon bring-up state: consecutive flip failures latch the flip
     * path off (stops per-present vblank spins swamping the work queue);
     * a vblank-wait timeout latches the tear-avoidance wait off. */
    ULONG HvsFlipFailCount;
    BOOLEAN HvsFlipBroken;
    BOOLEAN PvVBlankBroken;
    LONG HvsDiagPrints;              /* budget for first-N diagnostics  */

    BOOLEAN PixelValveValid;
    ULONG PixelValveIndex;
    PHYSICAL_ADDRESS PixelValvePhysical;
    ULONG PixelValveControl;
    ULONG PixelValveVControl;
    ULONG PixelValveVsyncEven;
    ULONG PixelValveHorzA;
    ULONG PixelValveHorzB;
    ULONG PixelValveVertA;
    ULONG PixelValveVertB;
    ULONG PixelValveHactAct;

    /* Hardware cursor composited by the HVS as a second display-list plane. */
    PVOID CursorVa;                   /* CPU mapping of the cursor surface      */
    PHYSICAL_ADDRESS CursorPhys;      /* physical base the HVS scans the cursor */
    ULONG CursorWidth;
    ULONG CursorHeight;
    LONG CursorX;                     /* top-left, screen coordinates          */
    LONG CursorY;
    LONG CursorHotX;
    LONG CursorHotY;
    BOOLEAN CursorVisible;
    BOOLEAN CursorShapeValid;

    /* ---- Wayland-style flip presents ------------------------------------
     * Display-only presents compose into an off-screen buffer of a private
     * triple-buffer ring and page-flip the HVS plane (pointer words latch at
     * frame start = atomic, tear-free). Per-buffer stale rects catch each
     * buffer up from pSource (always the complete frame). 0 count = fall
     * back to the classic blit-into-live-scanout path. */
    PVOID FlipBufVa;                  /* one WC region holding the ring     */
    PHYSICAL_ADDRESS FlipBufPhys;
    ULONG FlipBufSize;                /* bytes of ONE buffer                */
    ULONG FlipBufCount;               /* ring depth (3/2) or 0 = disabled   */
    ULONG FlipBufIndex;               /* buffer the HVS currently scans     */
    ULONG FlipsSinceVBlank;           /* pending unlatched flips            */
    BOOLEAN FlipPresentBroken;
    RECT FlipStale[3];                /* per-buffer catch-up bounding box   */

    /* ---- Local VRAM segment (segment 1) -------------------------------- */
    PVOID VramVa;                     /* write-combined kernel mapping     */
    PHYSICAL_ADDRESS VramPhysical;
    ULONG VramSize;

    /* ---- In-order submission/fence pipeline ---------------------------- */
    KSPIN_LOCK DmaLock;
    RPI5VC4_DMA_MAPPING DmaMappings[RPI5VC4_DMA_MAPPING_COUNT];
    ULONG DmaMappingNext;
    LONG V3dKickPrints;
    /* One in-order queue per GPU node; the engines run in parallel. */
    struct
    {
        RPI5VC4_PENDING_SUBMIT Pending[RPI5VC4_MAX_PENDING];
        ULONG Head;                   /* index of oldest pending submit    */
        ULONG Count;
    } NodeQueue[RPI5VC4_GPU_NODE_COUNT];
    ULONG LastCompletedFence;
    ULONG LastCompletedFencePerNode[RPI5VC4_GPU_NODE_COUNT];
    ULONG LastReportedFencePerNode[RPI5VC4_GPU_NODE_COUNT];
    KDPC FenceDpc;                    /* notifies dxgkrnl of completions   */
    KTIMER V3dPollTimer;              /* drives V3D job completion polling */
    KDPC V3dPollDpc;
    BOOLEAN StopAccepting;            /* set during StopDevice             */
    BOOLEAN DmaPipelineInitialized;

    /* Vsync source: refresh-rate timer polling the PixelValve VFP latch
     * (the root-enumerated devnode has no interrupt resource). */
    KTIMER VsyncTimer;
    KDPC VsyncDpc;
    BOOLEAN VsyncEnabled;

    /* ---- V3D 7.1 (3D engine) state -------------------------------------- */
    BOOLEAN V3dReady;
    BOOLEAN V3dNeedsSmsPulse;
    ULONG V3dVersion;
    ULONG V3dHubIdent[4];
    ULONG V3dCoreIdent[3];
    PVOID V3dSmsBase;
    PVOID V3dHubBase;
    PVOID V3dCoreBase;
    PULONG V3dPageTable;
    PHYSICAL_ADDRESS V3dPageTablePhys;
    PVOID V3dScratchPage;
    PHYSICAL_ADDRESS V3dScratchPagePhys;
    PVOID V3dOverflowVa;              /* binner overflow memory pool       */
    PHYSICAL_ADDRESS V3dOverflowPhys;
    ULONG V3dOverflowGpuVa;

    /* ---- VideoCore firmware property mailbox ---------------------------- */
    PVOID MboxBase;
    PVOID MboxBufferVa;               /* <4 GB contiguous property buffer  */
    PHYSICAL_ADDRESS MboxBufferPhys;
    ULONG FirmwareRevision;

    /* ---- V3D interrupt (SPI 250, DTB) — poll timer remains the backstop
     * because the ARM64 root IRQ arbiter may not grant the SPI. ---------- */
    PKINTERRUPT V3dInterrupt;
    PKINTERRUPT V3dInterrupt2;
    BOOLEAN V3dIrqConnected;
    volatile LONG V3dIsrCount;
    volatile LONG V3dIsrMasked;
    LONG V3dTdrPrints;
    LONG V3dQmaPrints;
    UCHAR HvsLptrsDead[2];
    LONG V3dOomPrints;
    ULONG V3dResetCount;
    volatile LONG V3dDpcFromIsr;
    ULONG V3dLastBfc;
    ULONG V3dLastRfc;
};

