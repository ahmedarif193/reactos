#pragma once

DEFINE_GUID(GUID_DEVINTERFACE_REACTOS_CYW43455_SDIO_CONTROL,
            0x82e34e79, 0x3ee9, 0x44e1, 0xa3, 0xd1, 0x40, 0x7d, 0x5d, 0x76, 0x53, 0x10);

#define CYW43455_SDIO_TRANSPORT_VERSION 1
#define CYW43455_SDIO_TRANSFER_WRITE 0x00000001
#define CYW43455_SDIO_TRANSFER_DIRECT 0x00000002
#define CYW43455_SDIO_TRANSFER_BLOCK_MODE 0x00000004
#define CYW43455_SDIO_TRANSFER_INCREMENT 0x00000008
#define CYW43455_SDIO_TRANSFER_VALID_FLAGS 0x0000000F
#define CYW43455_SDIO_MAX_TRANSFER 0x10000

typedef struct _CYW43455_SDIO_TRANSFER
{
    ULONG Version;
    ULONG Size;
    ULONG Flags;
    ULONG Address;
    ULONG Length;
    ULONG BlockSize;
    UCHAR Data[ANYSIZE_ARRAY];
} CYW43455_SDIO_TRANSFER, *PCYW43455_SDIO_TRANSFER;

#define CYW43455_SDIO_TRANSFER_HEADER_SIZE FIELD_OFFSET(CYW43455_SDIO_TRANSFER, Data)
#define CYW43455_SDIO_TRANSFER_SIZE(Length) (CYW43455_SDIO_TRANSFER_HEADER_SIZE + (Length))

#define IOCTL_CYW43455_SDIO_TRANSFER \
    CTL_CODE(FILE_DEVICE_NETWORK, 0x900, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)
