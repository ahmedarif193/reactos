/* Round constants. */
static const rsna_u8 g_Rcon[11] =
{
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36
};

/* GF(2^8) multiply by 2 (xtime). */
static rsna_u8 Xtime(rsna_u8 x)
{
    return (rsna_u8)((x << 1) ^ ((x >> 7) * 0x1b));
}

/* GF(2^8) multiply. */
static rsna_u8 GfMul(rsna_u8 a, rsna_u8 b)
{
    rsna_u8 p = 0;
    int i;
    for (i = 0; i < 8; i++)
    {
        if (b & 1)
            p ^= a;
        a = Xtime(a);
        b >>= 1;
    }
    return p;
}

static rsna_u32 SubWord(rsna_u32 w)
{
    return ((rsna_u32)g_Sbox[(w >> 24) & 0xFF] << 24) |
           ((rsna_u32)g_Sbox[(w >> 16) & 0xFF] << 16) |
           ((rsna_u32)g_Sbox[(w >> 8) & 0xFF] << 8) |
           ((rsna_u32)g_Sbox[w & 0xFF]);
}

static rsna_u32 RotWord(rsna_u32 w)
{
    return (w << 8) | (w >> 24);
}

int RsnaAesSetEncryptKey(RSNA_AES_KEY *key, const rsna_u8 *userKey, int keyBits)
{
    int Nk, Nr, i;
    rsna_u32 temp;
    rsna_u32 *rk = key->rk;
    int total;

    switch (keyBits)
    {
        case 128: Nk = 4; Nr = 10; break;
        case 192: Nk = 6; Nr = 12; break;
        case 256: Nk = 8; Nr = 14; break;
        default:  return -1;
    }

    key->rounds = Nr;

    for (i = 0; i < Nk; i++)
    {
        rk[i] = ((rsna_u32)userKey[4 * i] << 24) |
                ((rsna_u32)userKey[4 * i + 1] << 16) |
                ((rsna_u32)userKey[4 * i + 2] << 8) |
                ((rsna_u32)userKey[4 * i + 3]);
    }

    total = 4 * (Nr + 1);
    for (i = Nk; i < total; i++)
    {
        temp = rk[i - 1];
        if ((i % Nk) == 0)
            temp = SubWord(RotWord(temp)) ^ ((rsna_u32)g_Rcon[i / Nk] << 24);
        else if (Nk > 6 && (i % Nk) == 4)
            temp = SubWord(temp);
        rk[i] = rk[i - Nk] ^ temp;
    }

    return 0;
}

int RsnaAesSetDecryptKey(RSNA_AES_KEY *key, const rsna_u8 *userKey, int keyBits)
{
    /* InvCipher applies the inverse rounds directly, so the decrypt key
     * schedule equals the encrypt schedule. */
    return RsnaAesSetEncryptKey(key, userKey, keyBits);
}

/* State is a flat 16-byte column-major array per FIPS 197: s[r + 4c]. */

static void AddRoundKey(rsna_u8 s[16], const rsna_u32 *rk)
{
    int c;
    for (c = 0; c < 4; c++)
    {
        rsna_u32 w = rk[c];
        s[0 + 4 * c] ^= (rsna_u8)((w >> 24) & 0xFF);
        s[1 + 4 * c] ^= (rsna_u8)((w >> 16) & 0xFF);
        s[2 + 4 * c] ^= (rsna_u8)((w >> 8) & 0xFF);
        s[3 + 4 * c] ^= (rsna_u8)(w & 0xFF);
    }
}

static void SubBytes(rsna_u8 s[16])
{
    int i;
    for (i = 0; i < 16; i++)
        s[i] = g_Sbox[s[i]];
}

static void InvSubBytes(rsna_u8 s[16])
{
    int i;
    for (i = 0; i < 16; i++)
        s[i] = g_InvSbox[s[i]];
}

static void ShiftRows(rsna_u8 s[16])
{
    rsna_u8 t;

    /* Row 1: shift left by 1. */
    t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
    /* Row 2: shift left by 2. */
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    /* Row 3: shift left by 3 (== right by 1). */
    t = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = s[3]; s[3] = t;
}

static void InvShiftRows(rsna_u8 s[16])
{
    rsna_u8 t;

    /* Row 1: shift right by 1. */
    t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
    /* Row 2: shift right by 2. */
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    /* Row 3: shift right by 3 (== left by 1). */
    t = s[3]; s[3] = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = t;
}

static void MixColumns(rsna_u8 s[16])
{
    int c;
    for (c = 0; c < 4; c++)
    {
        rsna_u8 a0 = s[0 + 4 * c];
        rsna_u8 a1 = s[1 + 4 * c];
        rsna_u8 a2 = s[2 + 4 * c];
        rsna_u8 a3 = s[3 + 4 * c];

        s[0 + 4 * c] = (rsna_u8)(Xtime(a0) ^ (Xtime(a1) ^ a1) ^ a2 ^ a3);
        s[1 + 4 * c] = (rsna_u8)(a0 ^ Xtime(a1) ^ (Xtime(a2) ^ a2) ^ a3);
        s[2 + 4 * c] = (rsna_u8)(a0 ^ a1 ^ Xtime(a2) ^ (Xtime(a3) ^ a3));
        s[3 + 4 * c] = (rsna_u8)((Xtime(a0) ^ a0) ^ a1 ^ a2 ^ Xtime(a3));
    }
}

static void InvMixColumns(rsna_u8 s[16])
{
    int c;
    for (c = 0; c < 4; c++)
    {
        rsna_u8 a0 = s[0 + 4 * c];
        rsna_u8 a1 = s[1 + 4 * c];
        rsna_u8 a2 = s[2 + 4 * c];
        rsna_u8 a3 = s[3 + 4 * c];

        s[0 + 4 * c] = (rsna_u8)(GfMul(a0, 14) ^ GfMul(a1, 11) ^ GfMul(a2, 13) ^ GfMul(a3, 9));
        s[1 + 4 * c] = (rsna_u8)(GfMul(a0, 9)  ^ GfMul(a1, 14) ^ GfMul(a2, 11) ^ GfMul(a3, 13));
        s[2 + 4 * c] = (rsna_u8)(GfMul(a0, 13) ^ GfMul(a1, 9)  ^ GfMul(a2, 14) ^ GfMul(a3, 11));
        s[3 + 4 * c] = (rsna_u8)(GfMul(a0, 11) ^ GfMul(a1, 13) ^ GfMul(a2, 9)  ^ GfMul(a3, 14));
    }
}

void RsnaAesEncrypt(const RSNA_AES_KEY *key,
                    const rsna_u8 in[RSNA_AES_BLOCK_SIZE],
                    rsna_u8 out[RSNA_AES_BLOCK_SIZE])
{
    rsna_u8 s[16];
    int round;
    int i;

    for (i = 0; i < 16; i++)
        s[i] = in[i];

    AddRoundKey(s, &key->rk[0]);

    for (round = 1; round < key->rounds; round++)
    {
        SubBytes(s);
        ShiftRows(s);
        MixColumns(s);
        AddRoundKey(s, &key->rk[4 * round]);
    }

    SubBytes(s);
    ShiftRows(s);
    AddRoundKey(s, &key->rk[4 * key->rounds]);

    for (i = 0; i < 16; i++)
        out[i] = s[i];
}

void RsnaAesDecrypt(const RSNA_AES_KEY *key,
                    const rsna_u8 in[RSNA_AES_BLOCK_SIZE],
                    rsna_u8 out[RSNA_AES_BLOCK_SIZE])
{
    rsna_u8 s[16];
    int round;
    int i;

    for (i = 0; i < 16; i++)
        s[i] = in[i];

    AddRoundKey(s, &key->rk[4 * key->rounds]);

    for (round = key->rounds - 1; round >= 1; round--)
    {
        InvShiftRows(s);
        InvSubBytes(s);
        AddRoundKey(s, &key->rk[4 * round]);
        InvMixColumns(s);
    }

    InvShiftRows(s);
    InvSubBytes(s);
    AddRoundKey(s, &key->rk[0]);

    for (i = 0; i < 16; i++)
        out[i] = s[i];
}
